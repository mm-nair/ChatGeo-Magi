        user_message = {"content": prompt, "is_user": True}
        st.session_state.chat_history.append(user_message)
        
        display_chat_message(user_message, is_user=True)
        
        with st.chat_message("assistant"):
            with st.spinner("Thinking..."):
                try:
                    thread_id = f"streamlit_session_{st.session_state.get('session_id', 'default')}"
                    response = engine.stream_invoke(prompt, thread_id=thread_id)
                    processed_response = process_agent_response(response)
                    st.session_state.chat_history.append(processed_response)
                    display_chat_message(processed_response, is_user=False)
                    
                except Exception as e:
                    error_message = {
                        "final_response": f"Sorry, I encountered an error: {str(e)}",
                        "agent_steps": [{
                            "step_type": "error",
                            "content": traceback.format_exc(),
                            "tool_calls": [],
                            "observations": [],
                            "reasoning": ""
                        }],
                        "plots": []
                    }
                    
                    st.session_state.chat_history.append(error_message)
                    display_chat_message(error_message, is_user=False)
                    
                    st.error("An error occurred while processing your request.")
                    with st.expander("Debug Information"):
                        st.text(traceback.format_exc())

